import {
  LOCAL_MODEL_CONNECTIONS,
  LOCAL_ROOM_TASKS,
  LOCAL_ROOM_TASK_LIST,
  LOCAL_ADDRESSED_HISTORY,
  LOCAL_SERVICE_AUTHORITY,
  LOCAL_SERVICE_CONFIRMATIONS,
  LOCAL_SERVICE_METHODS,
  LOCAL_SERVICE_READ_METHODS,
  LOCAL_DECISION_METHODS,
  LOCAL_FINALIZATION_METHODS,
  LOCAL_PLUGIN_METHODS,
  LOCAL_PLUGIN_READ_METHODS,
  LOCAL_PLUGIN_SESSION_AUTHORITY,
  LOCAL_PROVIDER_METHODS,
  LOCAL_PROVIDER_READ_METHODS,
  LOCAL_RESTORE_METHODS,
  LOCAL_BROADCAST_METHODS,
  LOCAL_BROADCAST_READ_METHODS,
  LOCAL_ROOM_METHODS,
  PROFILE_METHODS,
} from '@runnets/contracts';

/** Authenticated method capability list; order starts with the identity probe contract. */
export function runtimeCapabilities(restore: boolean): readonly string[] {
  return [
    'status',
    'stop',
    'turns.submit',
    'desktop.assets',
    'receipts.get',
    'runs.get',
    ...LOCAL_ROOM_METHODS,
    ...LOCAL_DECISION_METHODS,
    'coding.panel',
    ...PROFILE_METHODS,
    ...LOCAL_RESTORE_METHODS,
    ...(restore ? LOCAL_PROVIDER_READ_METHODS : LOCAL_PROVIDER_METHODS),
    ...(restore ? LOCAL_PLUGIN_READ_METHODS : LOCAL_PLUGIN_METHODS),
    LOCAL_PLUGIN_SESSION_AUTHORITY,
    LOCAL_MODEL_CONNECTIONS,
    LOCAL_SERVICE_AUTHORITY,
    LOCAL_SERVICE_CONFIRMATIONS,
    LOCAL_ADDRESSED_HISTORY,
    ...(restore ? [] : [LOCAL_ROOM_TASKS, LOCAL_ROOM_TASK_LIST]),
    ...(restore ? LOCAL_SERVICE_READ_METHODS : LOCAL_SERVICE_METHODS),
    ...(restore ? LOCAL_BROADCAST_READ_METHODS : LOCAL_BROADCAST_METHODS),
    ...(restore ? [] : LOCAL_FINALIZATION_METHODS),
    ...(restore ? ['restore.maintenance'] : []),
  ];
}
